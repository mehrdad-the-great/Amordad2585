# Set: How to define a new set object
a = {}          # Dict: {}

b = dict()      # Dict: {}
c = set()       # Set: {}

d = {1:2}       # Dict
e = {1}         # Set

f = {1, 2, 3, } # Set

my_list = ['1', '2', 1, 2, ]
my_tuple = (1, 2, 3, '3', 'Hello', 4, 1)

g = set(my_list)    # Set
h = set(my_tuple)   # Set
